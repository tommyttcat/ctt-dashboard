import { NextResponse } from 'next/server';
import { kv } from '@vercel/kv';
import { SCANNER_SIP_META, SCANNER_DAILY_META, TOPMOVERS_META } from '@/lib/scanConfig';
import { CACHE, cacheHeaders, noCacheHeaders } from '@/lib/httpCache';
import { withOrb, etToday, freshestWatch, ORB_LIVE_KEY, type OrbWatchStatus } from '@/lib/orb';

// The function itself stays dynamic — every cache MISS reads KV fresh. What
// changed is that the response is now cacheable at the edge, so N concurrent
// users cost one KV read per TTL instead of nine reads each. See lib/httpCache.
export const dynamic = 'force-dynamic';
export const revalidate = 0;
export const fetchCache = 'force-no-store';

/** Stocks in Play / Daily rows never carry the scan's plan (its buy level is
 *  the day's high, after the move). Names on today's breakout watch keep their
 *  `_orb` state, which carries the tested entry — the opening-range high on
 *  volume — and the watch's stop; lib/scans/triggerProximity reads that. The
 *  analyst routine reads this route too, so it can no longer quote a day-high
 *  "buy above" for these names. */
const moversOnly = (rows: Record<string, unknown>[]) =>
  rows.map(r => (r && typeof r === 'object' && r.plan ? { ...r, plan: null, _mover: !r._orb } : r));

export async function GET() {
  try {
    // Pointing to the fresh _v6 keys generated by the new engine.
    // Parallel reads — these were sequential awaits, which meant six round
    // trips to KV on every poll from every open tab.
    const [
      dailySetups,
      stocksInPlay,
      topMovers,
      macroInsights,
      benchmark,
      benchmarks,
      lastScanTime,
      storedMeta,
      scanStreaks,
      highBeta,
      orbLive,
      /* One mget — a single KV command for all eleven keys (it was ten
         separate gets per cache miss). orb_live_v1 is the real-time breakout
         watch (/api/orb/live). */
    ] = await kv.mget<any[]>(
      'daily_setups_v6', 'stocks_in_play_v6', 'top_movers_v6', 'macro_insights_v6', 'benchmark_v6',
      'benchmarks_v1', 'last_scan_time_v6', 'scan_meta_v6', 'scan_streaks_v6', 'high_beta_v6', ORB_LIVE_KEY,
    );

    // Scan-gate metadata for the on-screen "?" key. Prefer whatever the last
    // run persisted — that is the config the scan ACTUALLY enforced. Fall back
    // to the static import so a cold KV (or a deploy before the first run)
    // still renders a key rather than an empty panel.
    /* Today's breakout watch rides the scan-meta write (lib/orb) so this
       route reads nothing extra for it; lifted out here so scanMeta stays the
       gate config it always was. */
    const { orbWatch: delayedWatch = null, earlyPool = null, ...metaRest } = (storedMeta ?? {}) as Record<string, unknown>;
    // Real time when /api/orb/live has run today, else the scanner's delayed status.
    const orbWatch = freshestWatch(orbLive as OrbWatchStatus | null, delayedWatch as OrbWatchStatus | null);
    const scanMeta = storedMeta && storedMeta.sip
      ? metaRest
      : { sip: SCANNER_SIP_META, daily: SCANNER_DAILY_META, topMovers: TOPMOVERS_META };

    /* PAYLOAD SIZE — this is the most-fetched route in the app, so what is NOT
       here matters as much as what is. Two fields were removed on 13 Aug 2026,
       taking the response from 394 KB to ~140 KB:

         liveChgMap  235 KB / 60% — the full live change map, 12,122 tickers, of
                     which only ~63 appeared anywhere else in this payload. Its
                     only consumer was MarketSummary, which used it to overlay
                     price onto multibagger / swing / consolidation rows. Those
                     routes now apply the overlay server-side themselves, the
                     way multibagger/latest and dvol/latest already did.
         sips         20 KB / 5% — a byte-identical duplicate of stocksInPlay.
                     Every consumer reads `stocksInPlay || sips`, so the alias
                     was pure weight on the wire.

       Do not reintroduce either without measuring first. Bandwidth here is paid
       per user per poll — it is the one cost the CDN cache does not flatten. */
    return NextResponse.json({
      success: true,
      lastScanTime: lastScanTime || Date.now(),
      /* Today's breakout state on the watch names (lib/orb withOrb) — from
         the orbWatch this route already read, so no extra KV. */
      /* Movers, not buys (lib/summary/rowFormat MOVER_SOURCES): these lists
         publish no plan unless the name is on today's breakout watch. */
      dailySetups: moversOnly(withOrb((dailySetups as Record<string, unknown>[]) || [], orbWatch, etToday())),
      stocksInPlay: moversOnly(withOrb((stocksInPlay as Record<string, unknown>[]) || [], orbWatch, etToday())),
      topMovers: topMovers || {
        'Mega Caps': [], 'Gainers': [], 'Losers': [], 'ETF Gainers': [], 'ETF Losers': []
      },
      macroInsights: macroInsights || null,
      benchmark: benchmark || null,
      benchmarks: benchmarks || (benchmark ? [benchmark] : []),
      scanMeta,
      scanStreaks: scanStreaks?.counts ?? {},
      highBeta: moversOnly((highBeta as Record<string, unknown>[]) || []),
      orbWatch,
      earlyPool,
    }, {
      headers: cacheHeaders(CACHE.LIVE),
    });

  } catch (error: any) {
    console.error("CRITICAL_LATEST_ROUTE_ERROR:", error);
    return NextResponse.json({ success: false, error: error.message }, {
      status: 500,
      headers: noCacheHeaders(),
    });
  }
}